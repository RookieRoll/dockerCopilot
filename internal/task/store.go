package task

import (
	"errors"
	"fmt"
	"os"
	"sort"
	"sync"
	"time"

	"github.com/google/uuid"
)

const (
	defaultRecordTTL      = 10 * time.Minute
	maxRecords            = 1000
	maxRecordBytes        = 1 << 20
	maxRecordTotalBytes   = 32 << 20
	maxSnapshotBytes      = 8 << 20
	maxSnapshotTotalBytes = 32 << 20
)

var ErrTaskNotFound = fmt.Errorf("task not found: %w", os.ErrNotExist)

// Options is kept source-compatible with older callers. Dir is intentionally
// ignored: task progress and rollback snapshots exist only in this process.
type Options struct {
	Dir   string
	Now   func() time.Time
	Warnf func(format string, args ...any)
}

type Store struct {
	mu          sync.Mutex
	now         func() time.Time
	records     map[string]Record
	recordBytes int
	snapshots   map[string][]byte
	closed      bool
}

func Open(opts Options) (*Store, error) {
	now := opts.Now
	if now == nil {
		now = time.Now
	}
	return &Store{
		now: now, records: make(map[string]Record), snapshots: make(map[string][]byte),
	}, nil
}

func (s *Store) Close() error {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.closed = true
	clear(s.records)
	clear(s.snapshots)
	s.recordBytes = 0
	return nil
}

func (s *Store) Create(r Record) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := s.ready(); err != nil {
		return err
	}
	if r.SchemaVersion == 0 {
		r.SchemaVersion = SchemaVersion
	}
	if !validTaskID(r.TaskID) {
		return errors.New("task ID must be generated by the caller as a canonical UUID")
	}
	if r.Status == "" {
		r.Status = StatusQueued
	}
	r.IsDone = r.Status.Terminal()
	now := s.now().UTC()
	if r.CreatedAt.IsZero() {
		r.CreatedAt = now
	}
	if r.UpdatedAt.IsZero() {
		r.UpdatedAt = now
	}
	if err := r.validate(); err != nil {
		return err
	}
	size := recordSize(r)
	if size > maxRecordBytes {
		return errors.New("task record exceeds in-memory size limit")
	}
	s.pruneLocked(now)
	if _, exists := s.records[r.TaskID]; exists {
		return errors.New("task already exists")
	}
	if !s.ensureRecordCapacityLocked("", size) {
		return errors.New("in-memory task capacity is full")
	}
	s.records[r.TaskID] = cloneRecord(r)
	s.recordBytes += size
	return nil
}

func (s *Store) Save(r Record) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := s.ready(); err != nil {
		return err
	}
	s.pruneLocked(s.now().UTC())
	if err := r.validate(); err != nil {
		return err
	}
	old, ok := s.records[r.TaskID]
	if !ok {
		return ErrTaskNotFound
	}
	if old.TaskID != r.TaskID || old.Type != r.Type || !old.CreatedAt.Equal(r.CreatedAt) || old.RequestID != r.RequestID || !optionsEqual(old.Options, r.Options) {
		return errors.New("task identity and request options are immutable")
	}
	if old.Status.Terminal() && old.Status != r.Status {
		return fmt.Errorf("terminal task status %q cannot change to %q", old.Status, r.Status)
	}
	r.IsDone = r.Status.Terminal()
	r.UpdatedAt = s.now().UTC()
	size := recordSize(r)
	if size > maxRecordBytes {
		return errors.New("task record exceeds in-memory size limit")
	}
	if !s.ensureRecordCapacityLocked(r.TaskID, size) {
		return errors.New("in-memory task capacity is full")
	}
	s.recordBytes += size - recordSize(old)
	s.records[r.TaskID] = cloneRecord(r)
	s.pruneLocked(s.now().UTC())
	return nil
}

func (s *Store) Get(id string) (Record, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := s.ready(); err != nil {
		return Record{}, err
	}
	s.pruneLocked(s.now().UTC())
	record, ok := s.records[id]
	if !ok {
		return Record{}, ErrTaskNotFound
	}
	return cloneRecord(record), nil
}

func (s *Store) List() ([]Record, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := s.ready(); err != nil {
		return nil, err
	}
	s.pruneLocked(s.now().UTC())
	result := make([]Record, 0, len(s.records))
	for _, record := range s.records {
		result = append(result, cloneRecord(record))
	}
	sort.Slice(result, func(i, j int) bool {
		if result[i].CreatedAt.Equal(result[j].CreatedAt) {
			return result[i].TaskID > result[j].TaskID
		}
		return result[i].CreatedAt.After(result[j].CreatedAt)
	})
	return result, nil
}

type ProtectedImage struct {
	TaskID  string
	ImageID string
}

func (s *Store) ProtectedImages() ([]ProtectedImage, error) {
	records, err := s.List()
	if err != nil {
		return nil, err
	}
	seen := make(map[string]struct{})
	result := make([]ProtectedImage, 0)
	for _, record := range records {
		if !protectsRecoveryImages(record) {
			continue
		}
		for _, id := range recordImageIDs(record) {
			key := record.TaskID + "\x00" + id
			if _, ok := seen[key]; ok {
				continue
			}
			seen[key] = struct{}{}
			result = append(result, ProtectedImage{TaskID: record.TaskID, ImageID: id})
		}
	}
	return result, nil
}

func (s *Store) ProtectedImageIDs() ([]string, error) {
	protected, err := s.ProtectedImages()
	if err != nil {
		return nil, err
	}
	set := make(map[string]struct{}, len(protected))
	for _, value := range protected {
		set[value.ImageID] = struct{}{}
	}
	result := make([]string, 0, len(set))
	for id := range set {
		result = append(result, id)
	}
	sort.Strings(result)
	return result, nil
}

func recordImageIDs(record Record) []string {
	seen := make(map[string]struct{})
	result := make([]string, 0, len(record.ImageIDs))
	add := func(id string) {
		if id == "" {
			return
		}
		if _, exists := seen[id]; exists {
			return
		}
		seen[id] = struct{}{}
		result = append(result, id)
	}
	for _, id := range record.ImageIDs {
		add(id)
	}
	for _, item := range record.Items {
		for _, id := range item.ImageIDs {
			add(id)
		}
	}
	return result
}

func protectsRecoveryImages(record Record) bool {
	if record.Status == StatusQueued || record.Status == StatusRunning || record.RequiresAttention || recoveryUnresolved(record.Recovery) {
		return true
	}
	for _, item := range record.Items {
		if item.RequiresAttention || itemRecoveryUnresolved(item) {
			return true
		}
	}
	return false
}

func (s *Store) SaveSnapshot(id string, content []byte) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := s.ready(); err != nil {
		return err
	}
	s.pruneLocked(s.now().UTC())
	if len(content) > maxSnapshotBytes {
		return errors.New("snapshot exceeds per-snapshot limit")
	}
	record, ok := s.records[id]
	if !ok {
		return ErrTaskNotFound
	}
	if record.Status != StatusQueued && record.Status != StatusRunning {
		return errors.New("snapshots can only be saved for active tasks")
	}
	key := snapshotKey(id, "")
	if _, exists := s.snapshots[key]; exists {
		return errors.New("snapshot already exists")
	}
	if s.snapshotBytesLocked()+len(content) > maxSnapshotTotalBytes {
		return errors.New("in-memory snapshot capacity is full")
	}
	s.snapshots[key] = append([]byte(nil), content...)
	return nil
}

func (s *Store) SaveItemSnapshot(taskID, snapshotID string, content []byte) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := s.ready(); err != nil {
		return err
	}
	s.pruneLocked(s.now().UTC())
	if !validTaskID(taskID) || !validTaskID(snapshotID) {
		return errors.New("invalid task or item snapshot ID")
	}
	if len(content) > maxSnapshotBytes {
		return errors.New("snapshot exceeds per-snapshot limit")
	}
	record, ok := s.records[taskID]
	if !ok || !recordReferencesItemSnapshot(record, snapshotID) {
		return errors.New("item snapshot reference is not owned by the task")
	}
	if record.Status != StatusQueued && record.Status != StatusRunning {
		return errors.New("item snapshots can only be saved for active tasks")
	}
	key := snapshotKey(taskID, snapshotID)
	if _, exists := s.snapshots[key]; exists {
		return errors.New("snapshot already exists")
	}
	if s.snapshotBytesLocked()+len(content) > maxSnapshotTotalBytes {
		return errors.New("in-memory snapshot capacity is full")
	}
	s.snapshots[key] = append([]byte(nil), content...)
	return nil
}

func (s *Store) ReadItemSnapshot(taskID, snapshotID string) ([]byte, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := s.ready(); err != nil {
		return nil, err
	}
	s.pruneLocked(s.now().UTC())
	record, ok := s.records[taskID]
	if !ok || !validTaskID(taskID) || !validTaskID(snapshotID) || !recordReferencesItemSnapshot(record, snapshotID) {
		return nil, errors.New("item snapshot reference is not owned by the task")
	}
	content, ok := s.snapshots[snapshotKey(taskID, snapshotID)]
	if !ok {
		return nil, errors.New("snapshot not found")
	}
	return append([]byte(nil), content...), nil
}

func (s *Store) ReadSnapshot(id string) ([]byte, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := s.ready(); err != nil {
		return nil, err
	}
	s.pruneLocked(s.now().UTC())
	if !validTaskID(id) {
		return nil, errors.New("invalid task ID")
	}
	content, ok := s.snapshots[snapshotKey(id, "")]
	if !ok {
		return nil, errors.New("snapshot not found")
	}
	return append([]byte(nil), content...), nil
}

func (s *Store) DeleteSnapshot(id string) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := s.ready(); err != nil {
		return err
	}
	s.pruneLocked(s.now().UTC())
	record, ok := s.records[id]
	if !ok {
		return ErrTaskNotFound
	}
	if err := record.snapshotDeletionAllowed(); err != nil {
		return err
	}
	delete(s.snapshots, snapshotKey(id, ""))
	return nil
}

func (s *Store) Delete(id string) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := s.ready(); err != nil {
		return err
	}
	s.pruneLocked(s.now().UTC())
	record, ok := s.records[id]
	if !ok {
		return ErrTaskNotFound
	}
	if err := record.snapshotDeletionAllowed(); err != nil {
		return err
	}
	delete(s.records, id)
	s.recordBytes -= recordSize(record)
	delete(s.snapshots, snapshotKey(id, ""))
	for _, item := range record.Items {
		delete(s.snapshots, snapshotKey(id, item.SnapshotRef))
	}
	return nil
}

func (s *Store) ready() error {
	if s.closed {
		return errClosed
	}
	return nil
}

func (s *Store) saveRecoveryCheckpoint(next Record) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := s.ready(); err != nil {
		return err
	}
	old, ok := s.records[next.TaskID]
	if !ok {
		return ErrTaskNotFound
	}
	if old.TaskID != next.TaskID || old.Type != next.Type || old.Status != next.Status || !old.CreatedAt.Equal(next.CreatedAt) {
		return errors.New("recovery checkpoint cannot alter task identity or status")
	}
	if err := next.validate(); err != nil {
		return err
	}
	size := recordSize(next)
	if size > maxRecordBytes {
		return errors.New("task record exceeds in-memory size limit")
	}
	if !s.ensureRecordCapacityLocked(next.TaskID, size) {
		return errors.New("in-memory task capacity is full")
	}
	s.records[next.TaskID] = cloneRecord(next)
	s.recordBytes += size - recordSize(old)
	return nil
}

func (s *Store) pruneLocked(now time.Time) {
	for id, record := range s.records {
		if terminalRecordEvictable(record) && now.Sub(terminalRetentionTime(record)) >= defaultRecordTTL {
			s.deleteRecordLocked(id, record)
			delete(s.snapshots, snapshotKey(id, ""))
			for _, item := range record.Items {
				delete(s.snapshots, snapshotKey(id, item.SnapshotRef))
			}
			continue
		}
	}
}

func (s *Store) ensureRecordCapacityLocked(replaceID string, incomingBytes int) bool {
	eligible := make([]Record, 0)
	count := len(s.records)
	total := s.recordBytes
	if existing, ok := s.records[replaceID]; replaceID != "" && ok {
		count--
		total -= recordSize(existing)
	}
	if count < maxRecords && total+incomingBytes <= maxRecordTotalBytes {
		return true
	}
	for _, record := range s.records {
		if record.TaskID != replaceID && terminalRecordEvictable(record) {
			eligible = append(eligible, record)
		}
	}
	sort.Slice(eligible, func(i, j int) bool {
		return terminalRetentionTime(eligible[i]).Before(terminalRetentionTime(eligible[j]))
	})
	for _, record := range eligible {
		if count < maxRecords && total+incomingBytes <= maxRecordTotalBytes {
			return true
		}
		s.deleteRecordLocked(record.TaskID, record)
		count--
		total -= recordSize(record)
		delete(s.snapshots, snapshotKey(record.TaskID, ""))
		for _, item := range record.Items {
			delete(s.snapshots, snapshotKey(record.TaskID, item.SnapshotRef))
		}
	}
	return count < maxRecords && total+incomingBytes <= maxRecordTotalBytes
}

func (s *Store) deleteRecordLocked(id string, record Record) {
	if _, ok := s.records[id]; ok {
		delete(s.records, id)
		s.recordBytes -= recordSize(record)
	}
}

func terminalRecordEvictable(record Record) bool {
	if !record.Status.Terminal() || record.RequiresAttention || len(record.ProtectedNames) != 0 || recoveryUnresolved(record.Recovery) {
		return false
	}
	for _, item := range record.Items {
		if item.RequiresAttention || len(item.ProtectedNames) != 0 || itemRecoveryUnresolved(item) {
			return false
		}
	}
	return true
}

func (s *Store) snapshotBytesLocked() int {
	total := 0
	for _, content := range s.snapshots {
		total += len(content)
	}
	return total
}

func recordSize(record Record) int { return len(mustMarshalRecord(record)) }

func mustMarshalRecord(record Record) []byte {
	encoded, err := encodeRecord(record)
	if err != nil {
		return nil
	}
	return encoded
}

func snapshotKey(taskID, snapshotID string) string { return taskID + ":" + snapshotID }

func recordReferencesItemSnapshot(record Record, snapshotID string) bool {
	if snapshotID == "" {
		return false
	}
	for _, item := range record.Items {
		if item.SnapshotRef == snapshotID {
			return true
		}
	}
	return false
}

func optionsEqual(a, b TaskOptions) bool {
	if a.Image != b.Image || a.TimeoutSeconds != b.TimeoutSeconds || a.HealthWaitSeconds != b.HealthWaitSeconds {
		return false
	}
	if a.DeleteOldContainer == nil || b.DeleteOldContainer == nil {
		return a.DeleteOldContainer == nil && b.DeleteOldContainer == nil
	}
	return *a.DeleteOldContainer == *b.DeleteOldContainer
}

func validTaskID(id string) bool {
	parsed, err := uuid.Parse(id)
	return err == nil && parsed.String() == id
}

func recoveryUnresolved(recovery Recovery) bool {
	return recovery.Status != "" && recovery.Status != "not-needed" && recovery.Status != "restored"
}

func (r Record) snapshotDeletionAllowed() error {
	if !r.Status.Terminal() || r.RequiresAttention || len(r.ProtectedNames) > 0 || recoveryUnresolved(r.Recovery) {
		return errors.New("snapshot or task is still protected by active recovery work")
	}
	for _, item := range r.Items {
		if item.RequiresAttention || len(item.ProtectedNames) > 0 || itemRecoveryUnresolved(item) {
			return errors.New("snapshot or task is still protected by batch item recovery work")
		}
	}
	return nil
}
