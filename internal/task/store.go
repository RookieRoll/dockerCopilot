type Options struct {
	Dir   string
	Now   func() time.Time
	Warnf func(format string, args ...any)
}

type Store struct {
	mu            sync.Mutex
	dir           string
	now           func() time.Time
	warnf         func(string, ...any)
	lock          *instanceLock
	closed        bool
	atomicReplace func(oldPath, newPath string) error
	dirSync       func(path string) error
	removePath    func(path string) error
}

func Open(opts Options) (*Store, error) {
	if strings.TrimSpace(opts.Dir) == "" {
		return nil, errors.New("task store directory is required")
	}
	dir, err := filepath.Abs(filepath.Clean(opts.Dir))
	if err != nil {
		return nil, fmt.Errorf("resolve task directory: %w", err)
	}
	if err = os.MkdirAll(dir, 0700); err != nil {
		return nil, fmt.Errorf("create task directory: %w", err)
	}
	st, err := os.Lstat(dir)
	if err != nil {
		return nil, err
	}
	if st.Mode()&os.ModeSymlink != 0 || !st.IsDir() {
		return nil, errors.New("task store path must be a real directory")
	}
	if err = os.Chmod(dir, 0700); err != nil {
		return nil, fmt.Errorf("restrict task directory permissions: %w", err)
	}
	lockPath := filepath.Join(dir, ".writer.lock")
	if lockInfo, lockErr := os.Lstat(lockPath); lockErr == nil {
		if lockInfo.Mode()&os.ModeSymlink != 0 || !lockInfo.Mode().IsRegular() {
			return nil, errors.New("task writer lock path must be a regular file")
		}
	} else if !errors.Is(lockErr, os.ErrNotExist) {
		return nil, lockErr
	}
	lock, err := acquireInstanceLock(lockPath)
	if err != nil {
		return nil, fmt.Errorf("task store is already open or cannot acquire writer lock: %w", err)
	}
	s := &Store{dir: dir, now: opts.Now, warnf: opts.Warnf, lock: lock, atomicReplace: os.Rename, dirSync: syncDir, removePath: os.Remove}
	if s.now == nil {
		s.now = time.Now
	}
	if s.warnf == nil {
		s.warnf = logx.Errorf
	}
	if err := s.quarantineCorrupt(); err != nil {
		_ = lock.Close()
		return nil, err
	}
	return s, nil
}

func (s *Store) Close() error {
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.closed {
		return nil
	}
	s.closed = true
	return s.lock.Close()
}

func (s *Store) Create(r Record) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := s.ready(); err != nil {
		return err
	}
	if r.SchemaVersion == 0 {
		r.SchemaVersion = SchemaVersion
	}
	if !validTaskID(r.TaskID) {
		return errors.New("task ID must be generated by the caller as a canonical UUID")
	}
	r.IsDone = r.Status.Terminal()
	now := s.now().UTC()
	if r.CreatedAt.IsZero() {
		r.CreatedAt = now
	}
	if r.UpdatedAt.IsZero() {
		r.UpdatedAt = now
	}
	if err := r.validate(); err != nil {
		return err
	}
	path := s.recordPath(r.TaskID)
	if _, err := os.Lstat(path); err == nil {
		return os.ErrExist
	} else if !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return s.writeRecord(r)
}

func (s *Store) Save(r Record) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := s.ready(); err != nil {
		return err
	}
	if err := r.validate(); err != nil {
		return err
	}
	old, err := s.readRecord(r.TaskID)
	if err != nil {
		return err
	}
	if old.TaskID != r.TaskID || old.Type != r.Type || !old.CreatedAt.Equal(r.CreatedAt) || old.RequestID != r.RequestID || !optionsEqual(old.Options, r.Options) {
		return errors.New("task identity and request options are immutable")
	}
	if old.Status.Terminal() && old.Status != r.Status {
		return fmt.Errorf("terminal task status %q cannot change to %q", old.Status, r.Status)
	}
	if old.Status.Terminal() {
		return errors.New("terminal task results are immutable; use Reconcile for verified recovery findings")
	}
	r.IsDone = r.Status.Terminal()
	r.UpdatedAt = s.now().UTC()
	return s.writeRecord(r)
}

type Reconciliation struct {
	Recovery          Recovery `json:"recovery,omitempty"`
	RequiresAttention bool     `json:"requiresAttention"`
	ProtectedNames    []string `json:"protectedNames,omitempty"`
	Error             string   `json:"error,omitempty"`
	// ClearPendingInstall is applied only after the candidate rollback has been
	// verified; timeout records retain this marker until reconciliation.
	ClearPendingInstall bool `json:"clearPendingInstall,omitempty"`
}

// Reconcile persists only read-only findings for an already terminal task.
func (s *Store) Reconcile(id string, finding Reconciliation) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := s.ready(); err != nil {
		return err
	}
	if !validTaskID(id) {
		return errors.New("invalid task ID")
	}
	old, err := s.readRecord(id)
	if err != nil {
		return err
	}
	if !old.Status.Terminal() {
		return errors.New("reconciliation requires a terminal task")
	}
	old.Recovery = finding.Recovery
	old.RequiresAttention = finding.RequiresAttention
	old.ProtectedNames = cloneStrings(finding.ProtectedNames)
	if finding.Error != "" {
		old.Error = finding.Error
	}
	if finding.ClearPendingInstall {
		old.PendingInstall = nil
	}
	old.UpdatedAt = s.now().UTC()
	return s.writeRecord(old)
}

func (s *Store) Get(id string) (Record, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := s.ready(); err != nil {
		return Record{}, err
	}
	if !validTaskID(id) {
		return Record{}, errors.New("invalid task ID")
	}
	return s.readRecord(id)
}

func (s *Store) List() ([]Record, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := s.ready(); err != nil {
		return nil, err
	}
	entries, err := os.ReadDir(s.dir)
	if err != nil {
		return nil, err
	}
	var records []Record
	for _, entry := range entries {
		name := entry.Name()
		if !strings.HasSuffix(name, ".json") {
			continue
		}
		id := strings.TrimSuffix(name, ".json")
		if !validTaskID(id) {
			s.warnf("ignoring task record with invalid filename %q", name)
			continue
		}
		r, err := s.readRecord(id)
		if err != nil {
			s.warnf("cannot read task record %s: %v", id, err)
			continue
		}
		records = append(records, r)
	}
	return records, nil
}

func (s *Store) SaveSnapshot(id string, content []byte) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := s.ready(); err != nil {
		return err
	}
	if !validTaskID(id) {
		return errors.New("invalid task ID")
	}
	r, err := s.readRecord(id)
	if err != nil {
		return err
	}
	if r.Status != StatusQueued && r.Status != StatusRunning {
		return errors.New("snapshots can only be saved for active tasks")
	}
	if _, err := os.Lstat(s.snapshotPath(id)); err == nil {
		return os.ErrExist
	} else if !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return s.atomicWrite(s.snapshotPath(id), content)
}

func (s *Store) ReadSnapshot(id string) ([]byte, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := s.ready(); err != nil {
		return nil, err
	}
	if !validTaskID(id) {
		return nil, errors.New("invalid task ID")
	}
	return readRegularFile(s.snapshotPath(id))
}

func (s *Store) DeleteSnapshot(id string) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := s.ready(); err != nil {
		return err
	}
	if !validTaskID(id) {
		return errors.New("invalid task ID")
	}
	r, err := s.readRecord(id)
	if err != nil {
		return err
	}
	if err := r.snapshotDeletionAllowed(); err != nil {
		return err
	}
	return removeRegularFile(s.snapshotPath(id))
}

// Delete removes only completed records that no longer carry recovery work.
func (s *Store) Delete(id string) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	if err := s.ready(); err != nil {
		return err
	}
	if !validTaskID(id) {
		return errors.New("invalid task ID")
	}
	r, err := s.readRecord(id)
	if err != nil {
		return err
	}
	if err := r.snapshotDeletionAllowed(); err != nil {
		return err
	}
	if err := removeRegularFile(s.snapshotPath(id)); err != nil {
		return err
	}
	return removeRegularFile(s.recordPath(id))
}

func (s *Store) ready() error {
	if s.closed {
		return errClosed
	}
	return nil
}
func (s *Store) recordPath(id string) string   { return filepath.Join(s.dir, id+".json") }
func (s *Store) snapshotPath(id string) string { return filepath.Join(s.dir, id+".snapshot") }

func (s *Store) writeRecord(r Record) error {
	b, err := encodeRecord(r)
	if err != nil {
		return err
	}
	return s.atomicWrite(s.recordPath(r.TaskID), b)
}

func (s *Store) atomicWrite(path string, data []byte) error {
	var previous []byte
	existed := false
	if fi, err := os.Lstat(path); err == nil {
		if fi.Mode()&os.ModeSymlink != 0 || !fi.Mode().IsRegular() {
			return errors.New("refusing to replace non-regular task file")
		}
		previous, err = readRegularFile(path)
		if err != nil {
			return err
		}
		existed = true
	} else if !errors.Is(err, os.ErrNotExist) {
		return err
	}
	tmp, err := os.CreateTemp(s.dir, ".task-tmp-*")
	if err != nil {
		return err
	}
	tmpPath := tmp.Name()
	defer os.Remove(tmpPath)
	if err = tmp.Chmod(0600); err == nil {
		_, err = tmp.Write(data)
	}
	if err == nil {
		err = tmp.Sync()
	}
	closeErr := tmp.Close()
	if err == nil {
		err = closeErr
	}
	if err != nil {
		return err
	}
	if err = s.atomicReplace(tmpPath, path); err != nil {
		return err
	}
	if err = s.dirSync(s.dir); err != nil {
		if existed {
			if rollbackErr := s.restoreFile(path, previous); rollbackErr != nil {
				return errors.Join(err, fmt.Errorf("restore previous task file after directory sync failure: %w", rollbackErr))
			}
		} else {
			if rollbackErr := s.removePath(path); rollbackErr != nil {
				return errors.Join(err, fmt.Errorf("remove uncommitted task file after directory sync failure: %w", rollbackErr))
			}
			if rollbackErr := s.dirSync(s.dir); rollbackErr != nil {
				return errors.Join(err, fmt.Errorf("sync directory after removing uncommitted task file: %w", rollbackErr))
			}
		}
		return err
	}
	return nil
}

func (s *Store) restoreFile(path string, data []byte) error {
	tmp, err := os.CreateTemp(s.dir, ".task-rollback-*")
	if err != nil {
		return err
	}
	tmpPath := tmp.Name()
	defer os.Remove(tmpPath)
	if err = tmp.Chmod(0600); err == nil {
		_, err = tmp.Write(data)
	}
	if err == nil {
		err = tmp.Sync()
	}
	closeErr := tmp.Close()
	if err == nil {
		err = closeErr
	}
	if err != nil {
		return err
	}
	if err = os.Rename(tmpPath, path); err != nil {
		return err
	}
	return s.dirSync(s.dir)
}

func (r Record) snapshotDeletionAllowed() error {
	if !r.Status.Terminal() || r.RequiresAttention || len(r.ProtectedNames) > 0 || recoveryUnresolved(r.Recovery) {
		return errors.New("snapshot or task is still protected by active recovery work")
	}
	return nil
}

func recoveryUnresolved(r Recovery) bool {
	return r.Status != "" && r.Status != "not-needed" && r.Status != "restored"
}

func optionsEqual(a, b TaskOptions) bool {
	if a.Image != b.Image || a.TimeoutSeconds != b.TimeoutSeconds || a.HealthWaitSeconds != b.HealthWaitSeconds {
		return false
	}
	if a.DeleteOldContainer == nil || b.DeleteOldContainer == nil {
		return a.DeleteOldContainer == nil && b.DeleteOldContainer == nil
	}
	return *a.DeleteOldContainer == *b.DeleteOldContainer
}

func (s *Store) readRecord(id string) (Record, error) {
	b, err := readRegularFile(s.recordPath(id))
	if err != nil {
		return Record{}, err
	}
	var r Record
	if err = json.Unmarshal(b, &r); err != nil {
		return Record{}, err
	}
	if err = r.validate(); err != nil {
		return Record{}, err
	}
	if r.TaskID != id {
		return Record{}, errors.New("task ID does not match filename")
	}
	return r, nil
}

func (s *Store) quarantineCorrupt() error {
	entries, err := os.ReadDir(s.dir)
	if err != nil {
		return err
	}
	var quarantine string
	for _, e := range entries {
		if !strings.HasSuffix(e.Name(), ".json") {
			continue
		}
		id := strings.TrimSuffix(e.Name(), ".json")
		if validTaskID(id) {
			if _, err := s.readRecord(id); err == nil {
				continue
			}
		}
		if quarantine == "" {
			quarantine = filepath.Join(s.dir, "corrupt")
			if err := os.MkdirAll(quarantine, 0700); err != nil {
				return err
			}
			qst, err := os.Lstat(quarantine)
			if err != nil || qst.Mode()&os.ModeSymlink != 0 || !qst.IsDir() {
				return errors.New("task corruption quarantine must be a real directory")
			}
			_ = os.Chmod(quarantine, 0700)
		}
		src := filepath.Join(s.dir, e.Name())
		fi, statErr := os.Lstat(src)
		if statErr != nil {
			s.warnf("corrupt task record %q could not be inspected: %v", e.Name(), statErr)
			continue
		}
		if fi.Mode()&os.ModeSymlink != 0 || !fi.Mode().IsRegular() {
			s.warnf("unsafe task record %q left in place", e.Name())
			continue
		}
		dst := filepath.Join(quarantine, e.Name()+"."+s.now().UTC().Format("20060102T150405.000000000"))
		if err := os.Rename(src, dst); err != nil {
			s.warnf("corrupt task record %q could not be quarantined: %v", e.Name(), err)
			continue
		}
		s.warnf("corrupt task record %q moved to quarantine", e.Name())
	}
	return nil
}

func validTaskID(id string) bool { u, err := uuid.Parse(id); return err == nil && u.String() == id }

func readRegularFile(path string) ([]byte, error) {
	before, err := os.Lstat(path)
	if err != nil {
		return nil, err
	}
	if before.Mode()&os.ModeSymlink != 0 || !before.Mode().IsRegular() {
		return nil, errors.New("task file is not a regular file")
	}
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	after, err := f.Stat()
	if err != nil {
		return nil, err
	}
	if !os.SameFile(before, after) {
		return nil, errors.New("task file changed while opening")
	}
	return io.ReadAll(f)
}

func removeRegularFile(path string) error {
	fi, err := os.Lstat(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	if fi.Mode()&os.ModeSymlink != 0 || !fi.Mode().IsRegular() {
		return errors.New("refusing to remove non-regular task file")
	}
	return os.Remove(path)
}
